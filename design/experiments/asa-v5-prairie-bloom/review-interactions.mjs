import { chromium } from '/Users/bukolaoludiran/Desktop/Jays-Lab/ASA-UI-UX/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const root = new URL('.', import.meta.url).pathname;
const browser = await chromium.launch({ headless: true });
const checks = [];
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' });
await page.keyboard.press('Tab');
assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Skip to content');
await page.keyboard.press('Enter');
assert.equal(await page.evaluate(() => location.hash), '#main');
assert.equal(await page.evaluate(() => document.activeElement.id), 'main');
checks.push('Keyboard skip link focuses main content.');
const summaries = page.locator('.service-list summary');
for (let i = 0; i < 3; i++) {
  const detail = page.locator('.service-list details').nth(i);
  const before = await detail.getAttribute('open');
  await summaries.nth(i).focus();
  await page.keyboard.press('Enter');
  assert.equal(await detail.getAttribute('open'), before === null ? '' : null);
  await page.keyboard.press('Enter');
}
checks.push('All three native service disclosures toggle by keyboard.');
for (const choice of ['Just because', 'A celebration', 'Something personal']) {
  await page.getByRole('button', { name: choice, exact: true }).click();
  assert.equal(await page.locator('[data-choice][aria-pressed="true"]').count(), 1);
  assert.equal(await page.getByRole('button', { name: choice, exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(decodeURIComponent((await page.locator('#occasion-email').getAttribute('href')).split('subject=')[1]), `Flowers — ${choice}`);
}
checks.push('All three occasion choices update single-selection state, live hint, and email subject.');
await page.locator('.service-list details').nth(1).locator('summary').click();
await page.getByRole('link', { name: 'Mark your moment' }).click();
assert.equal(await page.getByRole('button', { name: 'A celebration', exact: true }).getAttribute('aria-pressed'), 'true');
checks.push('Service inquiry link carries its occasion into the personal section.');
assert.equal(await page.locator('.contact-phone').getAttribute('href'), 'tel:+13065550101');
assert.equal(await page.locator('.contact-email').getAttribute('href'), 'mailto:hello@example.invalid');
checks.push('Reserved telephone and email targets are correct; no contact action was opened or sent.');
assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'auto');
checks.push('Reduced-motion preference disables smooth scrolling.');
await page.getByRole('button', { name: 'A celebration', exact: true }).focus();
await page.keyboard.press('Tab');
assert.equal(await page.evaluate(() => getComputedStyle(document.activeElement).outlineStyle), 'solid');
checks.push('Keyboard-focused controls show an explicit focus outline.');
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:5174/');
const toggle = page.getByRole('button', { name: /Menu/ });
await toggle.click();
assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
assert.equal(await page.locator('#navigation').isVisible(), true);
await page.screenshot({path: `${root}review/menu-open.png`});
await page.keyboard.press('Escape');
assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
assert.equal(await toggle.evaluate(element => element === document.activeElement), true);
await toggle.click();
await page.locator('#navigation').getByRole('link', { name: 'Make it personal' }).click();
assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
assert.equal(await page.evaluate(() => location.hash), '#personal');
await toggle.click();
await page.locator('.hero-bottom').click();
assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
checks.push('Mobile menu opens, Escape returns focus, section navigation closes it, and outside clicks dismiss it.');
await page.getByRole('button', { name: 'Something personal', exact: true }).click();
await page.locator('#personal').scrollIntoViewIfNeeded();
await page.screenshot({path: `${root}review/occasion-selected.png`});
await page.setViewportSize({ width: 600, height: 960 });
await page.goto('http://127.0.0.1:5174/');
await page.screenshot({path: `${root}review/intermediate-600.png`, fullPage: true});
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
checks.push('Intermediate 600px composition has no horizontal overflow.');
await page.emulateMedia({ reducedMotion: 'no-preference' });
assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'smooth');
checks.push('Normal-motion mode restores smooth anchor scrolling; no continuous animation exists.');
assert.deepEqual(errors, []);
checks.push('No browser runtime errors throughout interaction checks.');
await writeFile(`${root}review/interaction-results.json`, JSON.stringify({ ok: true, checks, runtimeErrors: errors }, null, 2));
console.log(JSON.stringify({ ok: true, checks: checks.length }));
await browser.close();
